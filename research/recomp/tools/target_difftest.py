#!/usr/bin/env python3
"""Differential test of lifted Victoria II functions against Unicorn.

This is a target-specific harness built on pcrecomp's lifter and the
semantics model used by tools/lift/difftest.py.  It lifts selected leaf
functions from v2game.exe, compiles them with the pcrecomp recomp32 runtime,
runs the original bytes under Unicorn and compares registers, flags, x87
depth and every byte of the 21 MiB guest window.
"""
import argparse
import json
import os
import struct
import subprocess
import sys
import tempfile

from common import ANALYSIS, PCRECOMP, WORK

import numpy as np
from capstone import Cs, CS_ARCH_X86, CS_MODE_32
from unicorn import Uc, UC_ARCH_X86, UC_MODE_32, UcError
from unicorn import x86_const as X
from tools.lift.lift32 import Lifter

PCRE = PCRECOMP
IMAGE = ANALYSIS / 'image.bin'
IMAGE_SIZE = os.path.getsize(IMAGE)
WIN_BASE = 0
WIN_SIZE = 0x01500000
STACK_TOP = 0x014EFFF8
SENTINEL = 0x00DEAD00
EFLAGS_START = 0x202
FPU_CONTROL_WORD = 0x027F
MXCSR = 0x1F80
REGS = ('eax', 'ecx', 'edx', 'ebx', 'esp', 'ebp', 'esi', 'edi')
UC_REGS = {
    'eax': X.UC_X86_REG_EAX, 'ecx': X.UC_X86_REG_ECX, 'edx': X.UC_X86_REG_EDX,
    'ebx': X.UC_X86_REG_EBX, 'esp': X.UC_X86_REG_ESP, 'ebp': X.UC_X86_REG_EBP,
    'esi': X.UC_X86_REG_ESI, 'edi': X.UC_X86_REG_EDI,
}
FLAGS = (('CF', 0), ('PF', 2), ('AF', 4), ('ZF', 6), ('SF', 7), ('DF', 10), ('OF', 11))

STATES = {
    0: dict(eax=0x00001234, ecx=4, edx=0x00005678, ebx=0x00001000,
            ebp=0x014EF000, esi=0x00010000, edi=0x00010100),
    1: dict(eax=0x00007FFF, ecx=1, edx=0x00008000, ebx=0x00002000,
            ebp=0x014EE000, esi=0x00010200, edi=0x00010300),
    2: dict(eax=0x0000FFFF, ecx=2, edx=0x0000FFFE, ebx=0x00005000,
            ebp=0x014ED000, esi=0x00010400, edi=0x00010500),
}

PRELUDE = r'''/* generated by target_difftest.py */
#define RECOMP_GENERATED_CODE
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "recomp_types.h"

uint32_t g_eax, g_ecx, g_edx, g_esp, g_ebx, g_esi, g_edi, g_ebp;
double   g_st[8];
int      g_fp_top;
uint16_t g_fpu_cw = 0x027F;
uint16_t g_seg_cs, g_seg_ds, g_seg_es, g_seg_fs, g_seg_gs, g_seg_ss;
uint32_t g_fs_base, g_gs_base, g_cur_func;
uint64_t g_mm[8];
xmm_t    g_xmm[8];
uint32_t g_mxcsr = 0x1F80;
ptrdiff_t g_mem_base;
void recomp_dump_trace(const char *why) { (void)why; }

#define WIN_BASE 0x%08Xu
#define WIN_SIZE 0x%08Xu
#define STACK_TOP 0x%08Xu
#define SENTINEL 0x%08Xu
#define IMAGE_SIZE %uu

static unsigned char *win, *ref;
static uint32_t out_eflags;

static void set_state(int state) {
    switch (state) {
    case 0:
        g_eax=0x00001234u; g_ecx=4; g_edx=0x00005678u; g_ebx=0x00001000u;
        g_ebp=0x014EF000u; g_esi=0x00010000u; g_edi=0x00010100u; break;
    case 1:
        g_eax=0x00007FFFu; g_ecx=1; g_edx=0x00008000u; g_ebx=0x00002000u;
        g_ebp=0x014EE000u; g_esi=0x00010200u; g_edi=0x00010300u; break;
    default:
        g_eax=0x0000FFFFu; g_ecx=2; g_edx=0x0000FFFEu; g_ebx=0x00005000u;
        g_ebp=0x014ED000u; g_esi=0x00010400u; g_edi=0x00010500u; break;
    }
    g_esp = STACK_TOP;
    *(uint32_t *)(win + STACK_TOP) = SENTINEL;
    g_fs_base = 0; g_gs_base = 0;
    g_seg_cs = g_seg_ds = g_seg_es = g_seg_fs = g_seg_gs = g_seg_ss = 0;
    g_fpu_cw = 0x027F; g_mxcsr = 0x1F80;
    memset(g_st, 0, sizeof g_st); g_fp_top = 0;
    memset(g_mm, 0, sizeof g_mm); memset(g_xmm, 0, sizeof g_xmm);
    g_cur_func = 0;
}

static void dump_case(int idx, int state) {
    int i; unsigned n = 0;
    printf("CASE %%d %%d\n", idx, state);
    printf("R %%08X %%08X %%08X %%08X %%08X %%08X %%08X %%08X\n",
           g_eax, g_ecx, g_edx, g_ebx, g_esp, g_ebp, g_esi, g_edi);
    printf("F %%08X\n", out_eflags);
    printf("T %%d\n", g_fp_top);
    if (memcmp(win, ref, WIN_SIZE) != 0) {
        for (i = 0; i < WIN_SIZE; i++) {
            if (win[i] != ref[i]) {
                printf("M %%08X %%02X\n", (unsigned)i, win[i]);
                if (++n >= 5000) { printf("MTRUNC\n"); break; }
            }
        }
    }
    printf("ENDCASE\n");
}
'''

CASE_TMPL = r'''
static void case_%d(void) {
    int _fpu_cmp = 0;
    uint32_t _cf = 0;
    int _df = 1;
    uint32_t _flag_a = 0, _flag_b = 0;
    uint32_t _flag_k = FK_NONE;
%s
    esp += 4; /* the dropped ret */
    out_eflags = recomp_eflags(_flag_k, _flag_a, _flag_b, _cf, _df);
}
'''

RUN_TMPL = r'''
static void run_%d(int state) {
    memcpy(win, ref, WIN_SIZE);
    set_state(state);
    out_eflags = 0;
    case_%d();
    dump_case(%d, state);
}
'''


def lift_bytes(code, va):
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    lifter = Lifter(precise_carry=False)
    lifter._labels = set()
    lifter._jump_targets = set()
    lifter._flag_state = None
    body = []
    seen = 0
    for insn in md.disasm(code, va):
        seen += insn.size
        if insn.mnemonic == 'ret':
            continue
        body.extend('    ' + line for line in lifter.lift_instruction(insn))
    if seen != len(code):
        raise RuntimeError(f'decoded {seen} of {len(code)} bytes at 0x{va:08X}')
    if any('UNIMPLEMENTED' in x for x in body):
        raise RuntimeError(f'UNIMPLEMENTED at 0x{va:08X}')
    return body


def build_c(targets, outdir):
    src = [PRELUDE % (WIN_BASE, WIN_SIZE, STACK_TOP, SENTINEL, IMAGE_SIZE)]
    for i, t in enumerate(targets):
        src.append(CASE_TMPL % (i, '\n'.join(lift_bytes(bytes.fromhex(t['bytes']), t['address']))))
        src.append(RUN_TMPL % (i, i, i))
    src.append('\nint main(int argc, char **argv) {\n'
               '    int idx = argc > 1 ? atoi(argv[1]) : 0;\n'
               '    int state = argc > 2 ? atoi(argv[2]) : 0;\n'
               '    FILE *f;\n'
               '    win = (unsigned char *)malloc(WIN_SIZE);\n'
               '    ref = (unsigned char *)malloc(WIN_SIZE);\n'
               '    if (!win || !ref) return 2;\n'
               '    memset(ref, 0, WIN_SIZE);\n'
               f'    f = fopen("{IMAGE}", "rb");\n'
               '    if (!f) return 3;\n'
               '    if (fread(ref + 0x400000, 1, IMAGE_SIZE, f) != IMAGE_SIZE) return 4;\n'
               '    fclose(f);\n'
               '    *(uint32_t *)(ref + STACK_TOP) = SENTINEL;\n'
               '    memcpy(win, ref, WIN_SIZE);\n'
               '    g_mem_base = (ptrdiff_t)win - (ptrdiff_t)WIN_BASE;\n'
               '    switch (idx) {\n')
    for i in range(len(targets)):
        src.append(f'    case {i}: run_{i}(state); break;\n')
    src.append('    default: return 5;\n'
               '    }\n'
               '    return 0;\n'
               '}\n')
    path = os.path.join(outdir, 'target_difftest.c')
    with open(path, 'w') as f:
        f.write(''.join(src))
    return path


def compile_c(src, outdir):
    include = os.path.join(PCRE, 'runtime', 'recomp32')
    exe = os.path.join(outdir, 'target_difftest')
    r = subprocess.run(['gcc', '-O0', '-g', '-w', '-I', include, src, '-o', exe],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f'gcc failed:\n{r.stdout}\n{r.stderr}')
    return exe


def run_unicorn(target, state):
    mu = Uc(UC_ARCH_X86, UC_MODE_32)
    mu.mem_map(WIN_BASE, WIN_SIZE)
    mu.mem_write(0x400000, open(IMAGE, 'rb').read())
    mu.mem_write(STACK_TOP, struct.pack('<I', SENTINEL))
    regs = dict(STATES[state])
    regs['esp'] = STACK_TOP
    for name, val in regs.items():
        mu.reg_write(UC_REGS[name], val)
    mu.reg_write(X.UC_X86_REG_EFLAGS, EFLAGS_START)
    mu.reg_write(X.UC_X86_REG_FPCW, FPU_CONTROL_WORD)
    mu.reg_write(X.UC_X86_REG_MXCSR, MXCSR)
    before = np.frombuffer(bytes(mu.mem_read(WIN_BASE, WIN_SIZE)), dtype=np.uint8).copy()
    try:
        mu.emu_start(target['address'], SENTINEL, count=200000)
    except UcError as e:
        return {'fault': str(e)}
    after = np.frombuffer(bytes(mu.mem_read(WIN_BASE, WIN_SIZE)), dtype=np.uint8)
    idx = np.flatnonzero(before != after)
    mem = {int(WIN_BASE + i): int(after[i]) for i in idx[:5000]}
    fpsw = mu.reg_read(X.UC_X86_REG_FPSW)
    return {
        'regs': {n: mu.reg_read(UC_REGS[n]) for n in REGS},
        'eflags': mu.reg_read(X.UC_X86_REG_EFLAGS),
        'fp_depth': (8 - ((fpsw >> 11) & 7)) & 7,
        'mem': mem,
        'mem_count': int(len(idx)),
    }


def parse_c(text):
    cur = None
    out = []
    for line in text.splitlines():
        p = line.split()
        if not p:
            continue
        if p[0] == 'CASE':
            cur = {'regs': {}, 'eflags': 0, 'fp_depth': 0, 'mem': {}, 'mem_count': 0}
        elif p[0] == 'R':
            cur['regs'] = {n: int(v, 16) for n, v in zip(REGS, p[1:])}
        elif p[0] == 'F':
            cur['eflags'] = int(p[1], 16)
        elif p[0] == 'T':
            cur['fp_depth'] = int(p[1])
        elif p[0] == 'M':
            cur['mem'][int(p[1], 16)] = int(p[2], 16)
            cur['mem_count'] += 1
        elif p[0] == 'MTRUNC':
            cur['mem_trunc'] = True
        elif p[0] == 'ENDCASE':
            out.append(cur)
    return out


def compare(c, u):
    fields = []
    for name in REGS:
        if c['regs'].get(name) != u['regs'].get(name):
            fields.append((name, f"{c['regs'].get(name, -1):08X}", f"{u['regs'].get(name, -1):08X}"))
    for name, bit in FLAGS:
        a = (c['eflags'] >> bit) & 1
        b = (u['eflags'] >> bit) & 1
        if a != b:
            fields.append((name, str(a), str(b)))
    if c['fp_depth'] != u['fp_depth']:
        fields.append(('x87 depth', str(c['fp_depth']), str(u['fp_depth'])))
    for addr in sorted(set(c['mem']) | set(u['mem'])):
        a, b = c['mem'].get(addr), u['mem'].get(addr)
        if a != b:
            fields.append((f'[{addr:08X}]', '--' if a is None else f'{a:02X}', '--' if b is None else f'{b:02X}'))
            if len(fields) > 50:
                break
    return fields


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--limit', type=int, default=40)
    ap.add_argument('--states', type=int, default=2)
    ap.add_argument('--out', default=str(ANALYSIS / 'difftest_results.json'))
    args = ap.parse_args()

    targets = json.load(open(ANALYSIS / 'difftest_targets.json'))[:args.limit]
    outdir = tempfile.mkdtemp(prefix='v2-difftest-')
    src = build_c(targets, outdir)
    exe = compile_c(src, outdir)
    print(f'compiled {exe} for {len(targets)} targets')

    results = []
    for i, t in enumerate(targets):
        for state in range(args.states):
            u = run_unicorn(t, state)
            rec = {'index': i, 'address': t['address_hex'], 'state': state, 'size': t['size']}
            if 'fault' in u:
                rec['status'] = 'unicorn_fault'
                rec['detail'] = u['fault']
                results.append(rec)
                print(f"SKIP {t['address_hex']} state={state} unicorn_fault {u['fault']}")
                continue
            r = subprocess.run([exe, str(i), str(state)], capture_output=True, text=True, timeout=60)
            if r.returncode != 0:
                rec['status'] = 'c_crash'
                rec['detail'] = f'returncode={r.returncode} stderr={r.stderr[-300:]}'
                results.append(rec)
                print(f"FAIL {t['address_hex']} state={state} c_crash rc={r.returncode}")
                continue
            parsed = parse_c(r.stdout)
            if len(parsed) != 1:
                rec['status'] = 'parse_error'
                rec['detail'] = r.stdout[-300:]
                results.append(rec)
                print(f"FAIL {t['address_hex']} state={state} parse_error")
                continue
            c = parsed[0]
            fields = compare(c, u)
            rec['fields'] = fields
            rec['mem_count_c'] = c.get('mem_count', 0)
            rec['mem_count_u'] = u.get('mem_count', 0)
            rec['status'] = 'ok' if not fields else 'diff'
            results.append(rec)
            if fields:
                print(f"DIFF {t['address_hex']} state={state}: " + '; '.join(f'{n} {a}/{b}' for n, a, b in fields[:8]))
            else:
                print(f"ok   {t['address_hex']} state={state} mem={u.get('mem_count',0)}")
    json.dump(results, open(args.out, 'w'), indent=1)
    ok = sum(1 for r in results if r['status'] == 'ok')
    diff = sum(1 for r in results if r['status'] == 'diff')
    skip = sum(1 for r in results if r['status'] == 'unicorn_fault')
    crash = sum(1 for r in results if r['status'] == 'c_crash')
    print(f'\nSUMMARY total={len(results)} ok={ok} diff={diff} unicorn_fault={skip} c_crash={crash}')
    print(f'results: {args.out}')
    print(f'source: {src}')


if __name__ == '__main__':
    main()
